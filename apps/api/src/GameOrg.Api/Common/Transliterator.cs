using System.Text;

namespace GameOrg.Api.Common;

/// <summary>
/// Транслитерация азербайджанских/русских букв в латиницу — для слагов
/// (<see cref="GameOrg.Api.Features.Venues.VenueSlugGenerator"/>) и хендлов
/// (<see cref="GameOrg.Api.Features.Identity.HandleGenerator"/>). Без неё
/// ToLowerInvariant + фильтр [a-z0-9] просто выбрасывает эти буквы:
/// "132-134 N-li məktəb" превращался в "132-134-n-li-m-kt-b".
/// ToLowerInvariant() сюда не годится сам по себе — турецкое/азербайджанское
/// İ (U+0130) сворачивается в "i" + отдельный комбинирующий значок, а не в
/// один символ "i", поэтому специальные буквы заменяются явной картой ДО
/// любого приведения регистра.
/// </summary>
public static class Transliterator
{
    private static readonly Dictionary<char, string> Map = new()
    {
        // Азербайджанский — буквы, которых нет в латинском [a-z].
        ['ə'] = "e", ['Ə'] = "e",
        ['ğ'] = "g", ['Ğ'] = "g",
        ['ı'] = "i", ['İ'] = "i",
        ['ö'] = "o", ['Ö'] = "o",
        ['ş'] = "s", ['Ş'] = "s",
        ['ü'] = "u", ['Ü'] = "u",
        ['ç'] = "c", ['Ç'] = "c",

        // Русский.
        ['а'] = "a", ['б'] = "b", ['в'] = "v", ['г'] = "g", ['д'] = "d",
        ['е'] = "e", ['ё'] = "e", ['ж'] = "zh", ['з'] = "z", ['и'] = "i",
        ['й'] = "y", ['к'] = "k", ['л'] = "l", ['м'] = "m", ['н'] = "n",
        ['о'] = "o", ['п'] = "p", ['р'] = "r", ['с'] = "s", ['т'] = "t",
        ['у'] = "u", ['ф'] = "f", ['х'] = "h", ['ц'] = "ts", ['ч'] = "ch",
        ['ш'] = "sh", ['щ'] = "sch", ['ъ'] = "", ['ы'] = "y", ['ь'] = "",
        ['э'] = "e", ['ю'] = "yu", ['я'] = "ya",
        ['А'] = "a", ['Б'] = "b", ['В'] = "v", ['Г'] = "g", ['Д'] = "d",
        ['Е'] = "e", ['Ё'] = "e", ['Ж'] = "zh", ['З'] = "z", ['И'] = "i",
        ['Й'] = "y", ['К'] = "k", ['Л'] = "l", ['М'] = "m", ['Н'] = "n",
        ['О'] = "o", ['П'] = "p", ['Р'] = "r", ['С'] = "s", ['Т'] = "t",
        ['У'] = "u", ['Ф'] = "f", ['Х'] = "h", ['Ц'] = "ts", ['Ч'] = "ch",
        ['Ш'] = "sh", ['Щ'] = "sch", ['Ъ'] = "", ['Ы'] = "y", ['Ь'] = "",
        ['Э'] = "e", ['Ю'] = "yu", ['Я'] = "ya",
    };

    /// <summary>
    /// Заменяет известные az/ru буквы на латинские эквиваленты, всё
    /// остальное (включая регистр) оставляет как есть — вызывающий код сам
    /// решает, когда переводить в lower и что делать с оставшимися символами.
    /// </summary>
    public static string Transliterate(string source)
    {
        var sb = new StringBuilder(source.Length);
        foreach (var ch in source)
            sb.Append(Map.TryGetValue(ch, out var replacement) ? replacement : ch.ToString());
        return sb.ToString();
    }
}
